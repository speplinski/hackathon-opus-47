// Bundles kernel modules into single-file Office Scripts.
//
// Office Scripts cannot import modules, so every dist file is the
// concatenation of types.ts, common.ts, the layer modules it needs and
// its entry file, with `import` lines removed and `export` keywords
// stripped. Top-level names must therefore be unique across modules.
//
// Usage: bun build.ts   (writes dist/*.ts, then type-checks each one)

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { spawnSync } from "child_process";

export const SCRIPTS: { [name: string]: string[] } = {
  // name of the Office Script in OneDrive -> modules (entry last)
  AD_Wejscie: ["l0_l3.ts", "entry_wejscie.ts"],
  AD_Audyt: ["l4.ts", "entry_audyt.ts"],
  AD_Uzgodnienie: ["l5.ts", "l6_l7.ts", "entry_uzgodnienie.ts"],
  AD_Petla: ["l8.ts", "verify.ts", "entry_petla.ts"],
  AD_Brief: ["brief.ts", "entry_brief.ts"],
  AD_Dowody: ["dowody.ts", "entry_dowody.ts"],
};

const HEADER = (name: string, mods: string[]): string =>
  [
    "// ------------------------------------------------------------------",
    `// ${name} — Auditable Design kernel (Office Script).`,
    "// Generated by copilot-studio/kernel/build.ts. Do not edit by hand:",
    `// edit src/{types,common,${mods.join(",")}} and rebuild.`,
    "// Paste the whole file into Excel on the web > Automate > New script.",
    "// ------------------------------------------------------------------",
    "",
  ].join("\n");

function strip(src: string): string {
  return src
    .replace(/^import\s[\s\S]*?from\s+["'][^"']+["'];?[ \t]*$/gm, "") // single- and multi-line imports
    .replace(/^import\s+["'][^"']+["'];?[ \t]*$/gm, "")
    .split("\n")
    .map((line) => line.replace(/^export\s+(?=(function|const|let|interface|type|class|enum)\b)/, ""))
    .join("\n");
}

if (import.meta.main) {
  mkdirSync("dist", { recursive: true });
  let failed = false;
  for (const [name, mods] of Object.entries(SCRIPTS)) {
    const parts = ["types.ts", "common.ts", ...mods].map((m) => {
      try {
        return `// ===== ${m} =====\n` + strip(readFileSync(`src/${m}`, "utf8"));
      } catch {
        return null;
      }
    });
    if (parts.some((p) => p === null)) {
      console.log(`skip ${name}: missing module(s)`);
      continue;
    }
    const out = `dist/${name}.ts`;
    writeFileSync(out, HEADER(name, mods) + parts.join("\n\n"));
    const tc = spawnSync(
      "tsc",
      ["--ignoreConfig", "--noEmit", "--strict", "--noImplicitAny", "--target", "ES2019", "--lib", "ES2019", "--skipLibCheck", "src/excelscript.d.ts", out],
      { encoding: "utf8" }
    );
    // Office Scripts rejects the `any` type explicitly.
    const anyHits = (readFileSync(out, "utf8").match(/:\s*any\b|<any>|as any\b/g) || []).length;
    if (tc.status !== 0 || anyHits > 0) {
      failed = true;
      console.log(`FAIL ${name}\n${tc.stdout}${tc.stderr}${anyHits ? `uses 'any' ${anyHits}x\n` : ""}`);
    } else {
      console.log(`ok   ${out}`);
    }
  }
  if (failed) process.exit(1);
}
